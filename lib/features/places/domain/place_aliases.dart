/// Azerbaijani / Turkish place names mapped to the spelling the geocoder knows.
///
/// Photon indexes OpenStreetMap's `name` plus the `de/en/fr/it` translations —
/// there is no `name:az` or `name:tr` in it. So a user typing their own
/// language got nothing ("Yunanıstan", "Vyana"), or worse, a coincidental match
/// somewhere else entirely ("Almaniya" → Albania, "Dubay" → a village in
/// Yemen). Rewriting the query before it leaves the app fixes that without a
/// paid geocoder or an extra network round trip.
///
/// Only names that differ from the English spelling need an entry; anything
/// already spelled internationally (Paris, London, Malta) passes through.
library;

/// Returns the international spelling for [query], or null when it isn't a
/// known local name and should be searched as typed.
///
/// Matches the whole query first, then — so autocomplete works while the user
/// is still typing — a prefix, but only when every alias starting with it means
/// the same place ("ital" → İtaliya / İtalya → Italy, whereas a prefix shared
/// by two different countries is left alone).
String? resolvePlaceAlias(String query) {
  final key = normalizePlaceQuery(query);
  if (key.isEmpty) return null;

  final exact = _aliases[key];
  if (exact != null) return exact;
  if (key.length < 4) return null;

  String? match;
  for (final entry in _aliases.entries) {
    if (!entry.key.startsWith(key)) continue;
    if (match != null && match != entry.value) return null;
    match = entry.value;
  }
  return match;
}

/// Lowercases [value] and folds the Azerbaijani/Turkish letters, so "İtaliya",
/// "italiya" and "ITALIYA" all reach the same key.
String normalizePlaceQuery(String value) {
  final buffer = StringBuffer();
  for (final rune in value.trim().toLowerCase().runes) {
    final char = String.fromCharCode(rune);
    buffer.write(_folded[char] ?? char);
  }
  return buffer.toString().replaceAll(RegExp(r'\s+'), ' ');
}

